#!/bin/sh
# Runs Ring Studio from source on Linux or macOS. The first run installs everything into .venv here.
set -e
cd "$(dirname "$0")"
if [ ! -d .venv ]; then
  python3 -m venv .venv
  .venv/bin/python -m pip install --upgrade pip
  .venv/bin/python -m pip install -r requirements.txt
fi
exec .venv/bin/python -m ring_studio
